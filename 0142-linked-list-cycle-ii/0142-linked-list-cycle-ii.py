# Definition for singly-linked list.
# class ListNode:
#     def __init__(self, x):
#         self.val = x
#         self.next = None

class Solution:
    def detectCycle(self, head: Optional[ListNode]) -> Optional[ListNode]:
        ptr_dict = {}
        temp = head
        index = 0
        while temp:
            if temp in ptr_dict:
                return temp
            ptr_dict[temp] = index
            temp = temp.next
            index = +1
        return None

