# Definition for singly-linked list.
# class ListNode:
#     def __init__(self, x):
#         self.val = x
#         self.next = None

class Solution:
    def detectCycle(self, head: Optional[ListNode]) -> Optional[ListNode]:
        ptrset = set()
        temp = head
        while temp:
            if temp in ptrset:
                return temp
            ptrset.add(temp)
            temp = temp.next
        return None

